function digitsOf(s: string): string {
  return (s.match(/\d+/g) || []).join("");
}

const byShort = new Map<string, FilialCatalogEntry>();
const officialBuckets = new Map<string, FilialCatalogEntry[]>();
for (const entry of FILIAL_CATALOG) {
  const shortKey = coreName(entry.short);
  if (shortKey && !byShort.has(shortKey)) byShort.set(shortKey, entry);
  const officialKey = coreName(entry.official);
  if (!officialKey) continue;
  const bucket = officialBuckets.get(officialKey) ?? [];
  bucket.push(entry);
  officialBuckets.set(officialKey, bucket);
}

function explicitCatalogNo(name: string): FilialCatalogEntry | null {
  const m =
    String(name).match(/(\d{1,3})\s*[-–]?\s*(?:filial|sonli)/i) ||
    String(name).match(/(?:filial|№)\s*(\d{1,3})/i);
  if (!m) return null;
  const no = Number(m[1]);
  return FILIAL_CATALOG.find((e) => e.no === no) ?? null;
}

function looseCatalog(key: string): FilialCatalogEntry | null {
  if (key.length < 4) return null;
  const keyDigits = digitsOf(key);
  const hits = FILIAL_CATALOG.filter((entry) => {
    const short = coreName(entry.short);
    if (short.length < 4) return false;
    const shortDigits = digitsOf(short);
    if (keyDigits !== shortDigits) return false;
    const contained = key.includes(short) || short.includes(key);
    if (!contained) return false;
    const gap = Math.abs(key.length - short.length);
    return gap <= 14;
  });
  if (hits.length === 1) return hits[0]!;
  return null;
}

/** Filial nomini katalogdagi raqamga bog‘laydi. O‘xshash, lekin boshqa filial aralashmaydi. */
export function matchFilialCatalog(name: string | null | undefined): FilialCatalogEntry | null {
  const raw = String(name || "");
  const key = coreName(raw);
  if (!key) return explicitCatalogNo(raw);
  const short = byShort.get(key);
  if (short) return short;
  const bucket = officialBuckets.get(key);
  if (bucket && bucket.length === 1) return bucket[0]!;
  return looseCatalog(key) ?? aliasByKey.get(key) ?? explicitCatalogNo(raw);
}

