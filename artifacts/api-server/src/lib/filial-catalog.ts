let assignOnce: Promise<void> | null = null;

/** Raqami yo‘q filiallarga katalogdan raqam yozadi. Jarayon davomida bir marta. */
export function ensureCatalogBranchNumbers(): Promise<void> {
  if (!assignOnce) {
    assignOnce = assignCatalogBranchNumbers().catch((err) => {
      assignOnce = null;
      throw err;
    });
  }
  return assignOnce;
}

async function assignCatalogBranchNumbers(): Promise<void> {
  const rows = await db
    .select({
      id: employeesTable.id,
      location: employeesTable.location,
      branchNo: employeesTable.branchNo,
      employmentStatus: employeesTable.employmentStatus,
    })
    .from(employeesTable)
    .where(eq(employeesTable.orgRole, "manager"));

  const used = new Set(rows.map((r) => r.branchNo).filter((n): n is number => n != null));
  let wrote = 0;
  for (const row of rows) {
    if (row.branchNo != null) continue;
    if (row.employmentStatus === "dismissed" || row.employmentStatus === "closed") continue;
    const name = displayBranchName(row.location);
    const hit = matchFilialCatalog(name);
    if (!hit || used.has(hit.no)) continue;
    await db.update(employeesTable).set({ branchNo: hit.no }).where(eq(employeesTable.id, row.id));
    used.add(hit.no);
    wrote += 1;
  }
  if (wrote > 0) {
    const { invalidateFilialBranchCache } = await import("./filial-bot-data");
    invalidateFilialBranchCache();
  }
}
